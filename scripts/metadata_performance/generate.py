#!/usr/bin/env python3
"""Regenerate the small correctness test and regression query definitions."""

from pathlib import Path

from workloads import SHAPES, delete_cases, delete_setup, expected_layout, layout_query, manifest_case


ROOT = Path(__file__).resolve().parents[2]


def statement(sql):
    return f"statement ok\n{sql};\n\n"


def query(sql, values):
    return f"query {'I' * len(values)}\n{sql};\n----\n" + "\t".join(map(str, values)) + "\n\n"


def main():
    target = (
        ROOT / "test/sql/local/catalog_test_config_setup/catalog_agnostic/delete/test_delete_planning_baseline.test"
    )
    text = f"""# name: {target.relative_to(ROOT)}
# group: [delete]

# Generated by scripts/metadata_performance/generate.py; edit workloads.py.
# Reduced #1654 correctness and physical-layout regression, with no timing gate.
require-env CATALOG_TEST_CONFIG_SETUP

require-env FORMAT_V3_SUPPORT

include test/sql/init_requires

require icu

"""
    text += statement("SET threads=1")
    text += statement("SET iceberg_use_server_side_scan_planning=false")
    for with_deletes in (True, False):
        table = "my_datalake.default.metadata_delete_" + ("baseline" if with_deletes else "control")
        shape = SHAPES["reduced"]
        for sql in delete_setup(shape, table, with_deletes):
            text += statement(sql)
        layout = expected_layout(shape, with_deletes)
        text += statement("BEGIN")
        text += query(layout_query(table), list(layout.values()))
        text += statement("COMMIT")
        text += query(f"SELECT count(*) FROM {table}", [layout["data_rows"] - layout["live_delete_entries"]])
        for case in delete_cases(shape, table, with_deletes):
            text += f"# {case['name']}: independently computed expected count.\n"
            text += statement(case["keys_sql"])
            text += query(case["sql"], [case["expected"]])
        text += statement(f"DROP TABLE {table}")
    target.write_text(text)

    directory = ROOT / "benchmark/metadata_performance"
    directory.mkdir(exist_ok=True)
    paths = []
    for with_deletes in (True, False):
        table = "my_datalake.default.metadata_delete_" + ("baseline" if with_deletes else "control")
        for case in delete_cases(SHAPES["regression"], table, with_deletes):
            if not with_deletes and case["name"] != "wide_in_no_deletes":
                continue
            path = directory / f"{case['name']}.benchmark"
            # Setup writes this load include from the existing fixture config. Keep
            # credentials/endpoints and catalog defaults out of the benchmark definitions.
            text = f"""# Generated by scripts/metadata_performance/generate.py; edit workloads.py.
name Iceberg metadata delete planning - {case['name']}
group metadata_performance
subgroup delete_planning

require avro

require parquet

require iceberg

require httpfs

include .catalogs/metadata-performance-regression/load.benchmark

init
{case['keys_sql']};

run
{case['sql']};

result I
{case['expected']}
"""
            path.write_text(text)
            paths.append(str(path.relative_to(ROOT)))
    path = directory / "manifest_1000.benchmark"
    path.write_text(
        f"""# Generated by scripts/metadata_performance/generate.py; edit workloads.py.
name Iceberg metadata manifest processing - 1000 entries
group metadata_performance
subgroup manifest_processing

require avro

require parquet

require iceberg

require httpfs

include .catalogs/metadata-performance-regression/load.benchmark

run
{manifest_case('my_datalake.default.metadata_manifest_1000')};

result I
1
"""
    )
    paths.append(str(path.relative_to(ROOT)))
    (ROOT / ".github/regression/metadata_performance.csv").write_text("\n".join(paths) + "\n")


if __name__ == "__main__":
    main()
